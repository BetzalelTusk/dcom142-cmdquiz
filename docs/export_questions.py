#!/usr/bin/env python3
"""Export the question bank from cmdquiz.py to docs/questions.js for the web version.

    python docs/export_questions.py

cmdquiz.py stays the single source of truth: run this after changing questions
(the GitHub Action does it automatically on every push that touches cmdquiz.py).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.argv = [sys.argv[0]]          # cmdquiz reads its flags from argv at import time
import cmdquiz  # noqa: E402

data = {
    "bank": [{k: q[k] for k in ("id", "topic", "prompt", "answers", "explain", "src", "why", "loose")} for q in cmdquiz.BANK],
    "topics": cmdquiz.TOPICS,
    "midterm": cmdquiz.MIDTERM,
    "ranks": cmdquiz.RANKS,
    "about": [{"title": t, "rows": [[lead, text] for lead, text in rows]} for t, rows in cmdquiz.ABOUT_PAGES],
}
out = os.path.join(HERE, "questions.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by docs/export_questions.py from cmdquiz.py. Do not edit by hand.\n")
    f.write("window.CMDQUIZ_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"wrote {os.path.relpath(out)}: {len(data['bank'])} questions")
